-- =============================================================================
-- Core schema: Driftwood Peak Coffee Co. (fictional specialty coffee roaster)
-- Sales channels: online shop, cafe counter, wholesale, monthly subscriptions
-- =============================================================================

create table public.categories (
    id          smallint generated by default as identity primary key,
    name        text not null unique,
    description text
);

create table public.products (
    id             integer generated by default as identity primary key,
    sku            text not null unique,
    name           text not null,
    category_id    smallint not null references public.categories (id),
    origin_country text,                                   -- null for blends / non-coffee
    roast_level    text check (roast_level in ('Light', 'Medium', 'Medium-Dark', 'Dark')),
    bag_size_g     integer check (bag_size_g > 0),          -- null for non-coffee
    unit_price     numeric(10, 2) not null check (unit_price >= 0),
    unit_cost      numeric(10, 2) not null check (unit_cost >= 0),
    is_active      boolean not null default true,
    created_at     timestamptz not null default now()
);

create table public.customers (
    id            integer generated by default as identity primary key,
    first_name    text not null,
    last_name     text not null,
    email         text not null unique,
    company_name  text,                                    -- wholesale accounts only
    customer_type text not null check (customer_type in ('Retail', 'Subscription', 'Wholesale')),
    city          text not null,
    state         text not null,
    country       text not null default 'United States',
    signup_date   date not null,
    created_at    timestamptz not null default now()
);

create table public.orders (
    id          bigint generated by default as identity primary key,
    customer_id integer not null references public.customers (id),
    order_date  timestamptz not null,
    channel     text not null check (channel in ('Online', 'Cafe', 'Wholesale', 'Subscription')),
    status      text not null default 'Completed' check (status in ('Completed', 'Refunded', 'Cancelled')),
    created_at  timestamptz not null default now()
);

create table public.order_items (
    id         bigint generated by default as identity primary key,
    order_id   bigint not null references public.orders (id) on delete cascade,
    product_id integer not null references public.products (id),
    quantity   integer not null check (quantity > 0),
    unit_price numeric(10, 2) not null,  -- price at time of sale
    unit_cost  numeric(10, 2) not null   -- cost at time of sale (for margin reporting)
);

create table public.inventory (
    product_id       integer primary key references public.products (id),
    quantity_on_hand integer not null check (quantity_on_hand >= 0),
    reorder_point    integer not null check (reorder_point >= 0),
    reorder_quantity integer not null check (reorder_quantity > 0),
    updated_at       timestamptz not null default now()
);

-- Every stock change is logged, so inventory can be audited / rebuilt.
create table public.inventory_movements (
    id            bigint generated by default as identity primary key,
    product_id    integer not null references public.products (id),
    movement_type text not null check (movement_type in ('Opening Balance', 'Sale', 'Restock')),
    quantity      integer not null,   -- positive = stock in, negative = stock out
    movement_date timestamptz not null,
    order_id      bigint references public.orders (id) on delete set null
);

create index orders_order_date_idx        on public.orders (order_date);
create index orders_customer_id_idx       on public.orders (customer_id);
create index order_items_order_id_idx     on public.order_items (order_id);
create index order_items_product_id_idx   on public.order_items (product_id);
create index inventory_movements_prod_idx on public.inventory_movements (product_id, movement_date);

comment on table public.orders is 'One row per customer order. Only Completed orders count as revenue.';
comment on table public.inventory_movements is 'Append-only stock ledger: sales, restocks and opening balances.';
